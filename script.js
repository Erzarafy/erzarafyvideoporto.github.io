async function closeVideo() {
  if (!videoDialog.open || dialogIsClosing) return;
  dialogIsClosing = true;
  dialogCloseRequested = true;
  dialogFrame.replaceChildren();
  if (activeDialogTransition) await waitForAnimation(activeDialogTransition.finished);
  if (activeDialogAnimation) await activeDialogAnimation;
  if (!videoDialog.open) return;
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const finishClose = () => {
    videoDialog.close();
    videoDialog.classList.remove("is-open", "is-animating-in", "is-animating-out");
  };

  if (!reducedMotion && document.startViewTransition && dialogTransitionName) {
    const transition = document.startViewTransition(() => {
      dialogFrame.style.removeProperty("--dialog-transition-name");
      if (lastFocusedElement instanceof HTMLElement) {
        lastFocusedElement.style.setProperty("--project-transition-name", dialogTransitionName);
      }
      finishClose();
    });
    activeDialogTransition = transition;
    await waitForAnimation(transition.finished);
    if (activeDialogTransition === transition) activeDialogTransition = null;
    clearDialogTransitionName();
  } else if (!reducedMotion) {
    videoDialog.classList.remove("is-open");
    videoDialog.classList.add("is-animating-out");
    await waitForAnimation(videoDialog.animate(
      [{ opacity: 1, transform: "scale(1)" }, { opacity: 0, transform: "scale(.96)" }],
      { duration: 180, easing: "cubic-bezier(0.65, 0, 0.35, 1)" }
    ));
    finishClose();
    clearDialogTransitionName();
  } else {
    finishClose();
    clearDialogTransitionName();
  }
  dialogIsClosing = false;
}

function observeReveals() {
  const elements = document.querySelectorAll('[data-reveal]:not([data-reveal="hero"])');
  if (!("IntersectionObserver" in window)) {
    elements.forEach((element) => element.classList.add("is-revealed"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-revealed");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  elements.forEach((element) => observer.observe(element));
}

function observeSectionLines() {
  const sections = document.querySelectorAll(".section");
  if (!("IntersectionObserver" in window)) {
    sections.forEach((section) => section.classList.add("section-line-ready"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("section-line-ready");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.05 });
  sections.forEach((section) => observer.observe(section));
}

function setCurrentNavigation(sectionId) {
  document.querySelectorAll('.main-nav a[href^="#"], .mobile-nav a[href^="#"]').forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionId}`;
    link.classList.toggle("is-current", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
}

function observeNavigationSections() {
  const sections = [...document.querySelectorAll("main > section[id]")];
  if (!("IntersectionObserver" in window)) return;

  const observer = new IntersectionObserver((entries) => {
    const current = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (current) setCurrentNavigation(current.target.id);
  }, { rootMargin: "-20% 0px -65% 0px", threshold: [0, 0.15, 0.35, 0.6] });
  sections.forEach((section) => observer.observe(section));
}

function setBackToTopVisible(backTop, visible) {
  backTop.classList.toggle("is-visible", visible);
  backTop.tabIndex = visible ? 0 : -1;
  backTop.setAttribute("aria-hidden", String(!visible));
}

function setupScrollMotion() {
  const header = document.querySelector(".site-header");
  const hero = document.querySelector(".hero");
  const progress = document.querySelector(".scroll-progress");
  const backTop = document.querySelector(".back-top");
  if (!header || !hero || !progress || !backTop) return;

  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  let previousScrollY = window.scrollY;
  let framePending = false;
  setBackToTopVisible(backTop, false);

  const updateScrollState = () => {
    const scrollY = window.scrollY;
    const maxScroll = document.documentElement.scrollHeight - window.innerHeight;
    const progressValue = maxScroll > 0 ? Math.min(scrollY / maxScroll, 1) : 0;
    progress.style.transform = `scaleX(${progressValue})`;

    header.classList.toggle("is-scrolled", scrollY > 24);
    setBackToTopVisible(backTop, scrollY > window.innerHeight);

    const heroPassed = hero.getBoundingClientRect().bottom <= header.offsetHeight;
    if (scrollY <= 24 || !heroPassed || reducedMotion.matches || scrollY < previousScrollY) {
      header.classList.remove("is-hidden");
      header.classList.add("is-visible");
    } else if (scrollY > previousScrollY) {
      header.classList.add("is-hidden");
      header.classList.remove("is-visible");
      if (mobileNav.classList.contains("open")) {
        mobileNav.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
        menuToggle.setAttribute("aria-label", "Buka menu");
      }
    }

    previousScrollY = scrollY;
    framePending = false;
  };
  const scheduleScrollUpdate = () => {
    if (framePending) return;
    framePending = true;
    requestAnimationFrame(updateScrollState);
  };

  window.addEventListener("scroll", scheduleScrollUpdate, { passive: true });
  window.addEventListener("resize", scheduleScrollUpdate, { passive: true });
  scheduleScrollUpdate();
}

function setupNavUnderline() {
  document.querySelectorAll(".main-nav a:not(.nav-cta)").forEach((link) => {
    let entryOrigin = "left";
    link.addEventListener("pointerenter", (event) => {
      const bounds = link.getBoundingClientRect();
      entryOrigin = event.clientX < bounds.left + bounds.width / 2 ? "left" : "right";
      link.style.setProperty("--underline-origin", entryOrigin);
    });
    link.addEventListener("pointerleave", () => {
      link.style.setProperty("--underline-origin", entryOrigin === "left" ? "right" : "left");
    });
  });
}

function animateCountUp() {
  const count = document.querySelector("[data-count-up]");
  if (!count) return;

  const target = Number(count.getAttribute("aria-label"));
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reducedMotion || !("IntersectionObserver" in window)) {
    count.textContent = String(target);
    return;
  }

  count.textContent = "0";
  const observer = new IntersectionObserver((entries) => {
    if (!entries.some((entry) => entry.isIntersecting)) return;
    observer.disconnect();
    const start = performance.now();
    const duration = 1200;

    function updateCount(now) {
      const progress = Math.min((now - start) / duration, 1);
      const eased = 1 - (1 - progress) ** 4;
      count.textContent = String(Math.round(target * eased));
      if (progress < 1) requestAnimationFrame(updateCount);
    }

    requestAnimationFrame(updateCount);
  }, { threshold: 0.15 });
  observer.observe(count);
}

function animateFrameNumber() {
  const frameNumber = document.querySelector("[data-frame-number]");
  if (!frameNumber) return;
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reducedMotion) {
    frameNumber.textContent = "024";
    return;
  }

  const start = performance.now();
  const duration = 700;
  function updateFrame(now) {
    const progress = Math.min((now - start) / duration, 1);
    const eased = 1 - (1 - progress) ** 4;
    frameNumber.textContent = String(1 + Math.round(23 * eased)).padStart(3, "0");
    if (progress < 1) requestAnimationFrame(updateFrame);
  }
  requestAnimationFrame(updateFrame);
}

