function applyTranslations(language = currentLanguage) {
  const languagePack = translations[language] || translations.id;
  document.documentElement.lang = language === "id" ? "id" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (languagePack[key]) {
      const countNode = key === "heroNote1" ? element.querySelector("[data-count-up]") : null;
      if (countNode) {
        countNode.textContent = "100";
        element.replaceChildren(countNode, document.createTextNode(languagePack[key].slice(3)));
        return;
      }
      element.textContent = languagePack[key];
    }
  });
  document.querySelectorAll(".lang-button").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function localizeProject(project, language = currentLanguage) {
  const localized = { ...project };
  const labels = categoryLabels[language] || categoryLabels.id;
  localized.categoryLabel = labels[project.category] || project.categoryLabel;
  return localized;
}

function formatCount(count) {
  return String(count).padStart(2, "0");
}

function renderProject(project, index) {
  const card = document.createElement("article");
  card.className = "project-card";
  card.dataset.projectId = project.driveId || project.youtubeId || project.title;

  const thumbnail = document.createElement("button");
  thumbnail.className = "project-thumb is-loading";
  thumbnail.type = "button";
  thumbnail.setAttribute("aria-label", `${translations[currentLanguage].playVideo} ${project.title}`);

  if (project.thumbnail) {
    const image = document.createElement("img");
    image.src = project.thumbnail;
    image.alt = "";
    image.loading = "lazy";
    image.addEventListener("load", () => {
      image.classList.add("is-loaded");
      thumbnail.classList.remove("is-loading");
    }, { once: true });
    image.addEventListener("error", () => {
      image.remove();
      thumbnail.classList.remove("is-loading");
      thumbnail.prepend(createFallback(project));
    }, { once: true });
    thumbnail.append(image);
    if (image.complete && image.naturalWidth > 0) {
      image.classList.add("is-loaded");
      thumbnail.classList.remove("is-loading");
    }
  } else {
    thumbnail.classList.remove("is-loading");
    thumbnail.append(createFallback(project));
  }

  const category = document.createElement("span");
  category.className = "project-badge";
  category.textContent = project.categoryLabel;
  thumbnail.append(category);

  if (project.duration) {
    const duration = document.createElement("span");
    duration.className = "project-length";
    duration.textContent = project.duration;
    thumbnail.append(duration);
  }

  const play = document.createElement("span");
  play.className = "project-play";
  play.setAttribute("aria-hidden", "true");
  play.textContent = "▶";
  thumbnail.append(play);

  const caption = document.createElement("span");
  caption.className = "project-thumb-caption";
  const title = document.createElement("strong");
  title.textContent = project.title;
  const year = document.createElement("span");
  year.textContent = project.year || "";
  caption.append(title, year);
  thumbnail.append(caption);
  thumbnail.addEventListener("click", () => openVideo(project, thumbnail));

  const info = document.createElement("div");
  info.className = "project-info";
  const heading = document.createElement("div");
  const client = document.createElement("p");
  client.className = "project-client";
  client.textContent = project.client || "SELECTED WORK";
  const projectTitle = document.createElement("h3");
  projectTitle.className = "project-title";
  projectTitle.textContent = project.title;
  heading.append(client, projectTitle);
  info.append(heading);

  if (project.description) {
    const description = document.createElement("p");
    description.className = "project-description";
    description.textContent = project.description;
    info.append(description);
  }

  card.append(thumbnail, info);
  return card;
}

function createFallback(project) {
  const fallback = document.createElement("span");
  fallback.className = "project-fallback";
  fallback.style.setProperty("--project-glow", project.glow || "rgba(205,243,107,.2)");
  fallback.setAttribute("aria-hidden", "true");
  const mark = document.createElement("span");
  mark.textContent = project.mark || "ERZA.";
  fallback.append(mark);
  return fallback;
}

function observeProjectCards() {
  if (!("IntersectionObserver" in window)) {
    projectGrid.querySelectorAll(".project-card").forEach((card) => card.classList.add("is-revealed"));
    return;
  }
  if (!projectCardObserver) {
    projectCardObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-revealed");
          projectCardObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.15 });
  }
  projectGrid.querySelectorAll(".project-card:not(.is-revealed)").forEach((card) => projectCardObserver.observe(card));
}

async function renderProjects(filter = "all", { animate = false } = {}) {
  const renderVersion = ++projectRenderVersion;
  const previousCards = [...projectGrid.querySelectorAll(".project-card")];
  const oldPositions = new Map(previousCards.map((card) => [
    card.dataset.projectId,
    card.getBoundingClientRect()
  ]));
  if (animate && previousCards.length) {
    const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    await Promise.all(previousCards.map((card) => card.animate(
      reducedMotion
        ? [{ opacity: 1 }, { opacity: 0 }]
        : [{ opacity: 1, transform: "scale(1)" }, { opacity: 0, transform: "scale(.98)" }],
      { duration: 150, easing: "ease-out", fill: "forwards" }
    ).finished));
    if (renderVersion !== projectRenderVersion) return;
    previousCards.forEach((card) => card.getAnimations().forEach((animation) => animation.cancel()));
  }

  const existingCards = new Map(previousCards.map((card) => [card.dataset.projectId, card]));
  const visibleProjects = videoProjects
    .map((project) => localizeProject(project, currentLanguage))
    .filter((project) => filter === "all" || project.category === filter);

  const cards = visibleProjects.map((project, index) => {
    const key = project.driveId || project.youtubeId || project.title;
    const isNew = !existingCards.has(key);
    const card = existingCards.get(key) || renderProject(project, index);
    card.querySelector(".project-badge").textContent = project.categoryLabel;
    card.querySelector(".project-thumb").setAttribute("aria-label", `${translations[currentLanguage].playVideo} ${project.title}`);
    return { card, key, index, isNew };
  });
  projectGrid.replaceChildren(...cards.map(({ card }) => card));

  if (animate && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    cards.forEach(({ card, key, index, isNew }) => {
      card.classList.add("is-revealed");
      const oldPosition = oldPositions.get(key);
      const newPosition = card.getBoundingClientRect();
      if (oldPosition && !isNew) {
        const deltaX = oldPosition.left - newPosition.left;
        const deltaY = oldPosition.top - newPosition.top;
        const inViewport = newPosition.bottom > 0 && newPosition.top < window.innerHeight;
        if ((deltaX || deltaY) && inViewport) {
          card.animate(
            [{ transform: `translate(${deltaX}px, ${deltaY}px)` }, { transform: "translate(0, 0)" }],
            { duration: 450, easing: "cubic-bezier(0.16, 1, 0.3, 1)" }
          );
        }
      } else if (newPosition.bottom > 0 && newPosition.top < window.innerHeight) {
        card.animate(
          [{ opacity: 0, transform: "translateY(10px) scale(.99)" }, { opacity: 1, transform: "translateY(0) scale(1)" }],
          { duration: 300, delay: Math.min(index, 5) * 40, easing: "cubic-bezier(0.16, 1, 0.3, 1)" }
        );
      } else if (isNew) {
        card.classList.remove("is-revealed");
      }
    });
  }
  projectGrid.hidden = visibleProjects.length === 0;
  emptyState.hidden = visibleProjects.length !== 0;
  if (!emptyState.hidden) {
    /* Fase 4 — mark empty state muncul sekali dengan halus tiap ditampilkan */
    const mark = emptyState.querySelector(".empty-mark");
    if (mark) {
      mark.classList.remove("is-popping");
      void mark.offsetWidth; /* paksa reflow agar animasi bisa di-restart */
      mark.classList.add("is-popping");
    }
  }
  observeProjectCards();
}

function moveFilterPill(activeButton) {
  const options = activeButton.closest(".filter-options");
  const pill = options.querySelector(".filter-pill");
  const width = activeButton.offsetWidth;
  pill.style.height = `${activeButton.offsetHeight}px`;
  pill.style.transform = `translate3d(${activeButton.offsetLeft}px, ${activeButton.offsetTop}px, 0) scaleX(${width})`;
  options.classList.add("has-pill");
}

