const projectGrid = document.getElementById("projectGrid");
const emptyState = document.getElementById("emptyState");
const filterButtons = [...document.querySelectorAll(".filter-button")];
const videoDialog = document.getElementById("videoDialog");
const dialogFrame = document.getElementById("dialogFrame");
const dialogTitle = document.getElementById("dialogTitle");
let lastFocusedElement = null;

function applyTranslations(language = currentLanguage) {
  const languagePack = translations[language] || translations.id;
  document.documentElement.lang = language === "id" ? "id" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (languagePack[key]) {
      element.textContent = languagePack[key];
    }
  });
  document.querySelectorAll(".lang-button").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function localizeProject(project, language = currentLanguage) {
  const localized = { ...project };
  const labels = categoryLabels[language] || categoryLabels.id;
  localized.categoryLabel = labels[project.category] || project.categoryLabel;
  return localized;
}

function formatCount(count) {
  return String(count).padStart(2, "0");
}

function renderProject(project, index) {
  const card = document.createElement("article");
  card.className = "project-card";
  card.style.animationDelay = `${Math.min(index, 6) * 55}ms`;

  const thumbnail = document.createElement("button");
  thumbnail.className = "project-thumb";
  thumbnail.type = "button";
  thumbnail.setAttribute("aria-label", `${translations[currentLanguage].playVideo} ${project.title}`);

  if (project.thumbnail) {
    const image = document.createElement("img");
    image.src = project.thumbnail;
    image.alt = "";
    image.loading = "lazy";
    image.addEventListener("error", () => {
      image.remove();
      thumbnail.prepend(createFallback(project));
    }, { once: true });
    thumbnail.append(image);
  } else {
    thumbnail.append(createFallback(project));
  }

  const category = document.createElement("span");
  category.className = "project-badge";
  category.textContent = project.categoryLabel;
  thumbnail.append(category);

  if (project.duration) {
    const duration = document.createElement("span");
    duration.className = "project-length";
    duration.textContent = project.duration;
    thumbnail.append(duration);
  }

  const play = document.createElement("span");
  play.className = "project-play";
  play.setAttribute("aria-hidden", "true");
  play.textContent = "▶";
  thumbnail.append(play);

  const caption = document.createElement("span");
  caption.className = "project-thumb-caption";
  const title = document.createElement("strong");
  title.textContent = project.title;
  const year = document.createElement("span");
  year.textContent = project.year || "";
  caption.append(title, year);
  thumbnail.append(caption);
  thumbnail.addEventListener("click", () => openVideo(project));

  const info = document.createElement("div");
  info.className = "project-info";
  const heading = document.createElement("div");
  const client = document.createElement("p");
  client.className = "project-client";
  client.textContent = project.client || "SELECTED WORK";
  const projectTitle = document.createElement("h3");
  projectTitle.className = "project-title";
  projectTitle.textContent = project.title;
  heading.append(client, projectTitle);
  info.append(heading);

  if (project.description) {
    const description = document.createElement("p");
    description.className = "project-description";
    description.textContent = project.description;
    info.append(description);
  }

  card.append(thumbnail, info);
  return card;
}

function createFallback(project) {
  const fallback = document.createElement("span");
  fallback.className = "project-fallback";
  fallback.style.setProperty("--project-glow", project.glow || "rgba(205,243,107,.2)");
  fallback.setAttribute("aria-hidden", "true");
  const mark = document.createElement("span");
  mark.textContent = project.mark || "ERZA.";
  fallback.append(mark);
  return fallback;
}

function renderProjects(filter = "all") {
  const visibleProjects = videoProjects
    .map((project) => localizeProject(project, currentLanguage))
    .filter((project) => filter === "all" || project.category === filter);
  projectGrid.replaceChildren(...visibleProjects.map(renderProject));
  projectGrid.hidden = visibleProjects.length === 0;
  emptyState.hidden = visibleProjects.length !== 0;
}

function updateFilterCounts() {
  document.querySelector('[data-count="all"]').textContent = formatCount(videoProjects.length);
  for (const filter of filterButtons) {
    const category = filter.dataset.filter;
    if (category !== "all") {
      const count = videoProjects.filter((project) => project.category === category).length;
      const countNode = filter.querySelector('[data-count]');
      if (countNode) {
        countNode.textContent = formatCount(count);
      }
      filter.hidden = count === 0;
    }
  }
}

function openVideo(project) {
  lastFocusedElement = document.activeElement;
  dialogTitle.textContent = `MENONTON · ${project.title.toUpperCase()}`;
  const iframe = document.createElement("iframe");
  iframe.src = project.source === "drive"
    ? `https://drive.google.com/file/d/${encodeURIComponent(project.driveId)}/preview`
    : `https://www.youtube-nocookie.com/embed/${encodeURIComponent(project.youtubeId)}?autoplay=1&rel=0`;
  iframe.title = project.title;
  iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture";
  iframe.referrerPolicy = "strict-origin-when-cross-origin";
  iframe.allowFullscreen = true;
  dialogFrame.replaceChildren(iframe);
  videoDialog.showModal();
  document.body.classList.add("dialog-open");
  document.getElementById("closeDialog").focus();
}

function closeVideo() {
  if (!videoDialog.open) return;
  dialogFrame.replaceChildren();
  videoDialog.close();
}

for (const filter of filterButtons) {
  filter.addEventListener("click", () => {
    for (const button of filterButtons) {
      const isActive = button === filter;
      button.classList.toggle("is-active", isActive);
      button.setAttribute("aria-pressed", String(isActive));
    }
    renderProjects(filter.dataset.filter);
  });
}

document.getElementById("closeDialog").addEventListener("click", closeVideo);
videoDialog.addEventListener("click", (event) => {
  if (event.target === videoDialog) closeVideo();
});
videoDialog.addEventListener("close", () => {
  dialogFrame.replaceChildren();
  document.body.classList.remove("dialog-open");
  lastFocusedElement?.focus();
});

const menuToggle = document.getElementById("menuToggle");
const mobileNav = document.getElementById("mainNav");

menuToggle.addEventListener("click", () => {
  const isOpen = mobileNav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? "Tutup menu" : "Buka menu");
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    if (videoDialog.open) {
      closeVideo();
      return;
    }
    if (mobileNav.classList.contains("open")) {
      mobileNav.classList.remove("open");
      menuToggle.setAttribute("aria-expanded", "false");
      menuToggle.setAttribute("aria-label", "Buka menu");
      menuToggle.focus();
    }
  }
});

mobileNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    mobileNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", "Buka menu");
  });
});

document.querySelectorAll(".lang-button").forEach((button) => {
  button.addEventListener("click", () => {
    currentLanguage = button.dataset.lang;
    applyTranslations(currentLanguage);
    renderProjects(document.querySelector(".filter-button.is-active")?.dataset.filter || "all");
  });
});

applyTranslations();
updateFilterCounts();
renderProjects();
